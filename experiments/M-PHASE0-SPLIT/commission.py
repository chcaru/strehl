"""Commission the Rust split-spectrum instrument before real captures.

The four named defects are injected through a test-only environment seam.  A
plant counts only when cargo returns its exact test-failure code (101).  The
fixed-array FFT comparison is independently recomputed here by direct DFT; it
does not call the Rust transform or consume data generated by it.
"""

from __future__ import annotations

import cmath
import csv
import io
import json
import math
import os
import re
import struct
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "out"
PLANT_ENV = "STREHL_SPLIT_TEST_PLANT"


def run(args: list[str], plant: str | None = None) -> tuple[int, str]:
    env = os.environ.copy()
    if plant is None:
        env.pop(PLANT_ENV, None)
    else:
        env[PLANT_ENV] = plant
    proc = subprocess.run(
        args,
        cwd=ROOT,
        env=env,
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )
    return proc.returncode, proc.stdout


def f32(value: float) -> float:
    return struct.unpack("<f", struct.pack("<f", value))[0]


def fixed_planes(n: int = 8) -> tuple[list[float], list[float]]:
    a: list[float] = []
    b: list[float] = []
    for y in range(n):
        for x in range(n):
            shared = (
                math.sin(2.0 * math.pi * x / n)
                + 0.35 * math.cos(2.0 * math.pi * (x + 2.0 * y) / n)
                + 0.03 * x * y
            )
            independent = 0.17 * math.sin(2.0 * math.pi * (3.0 * x + y) / n)
            a.append(f32(shared))
            b.append(f32(0.8 * shared + independent))
    return a, b


def direct_dft_rings(a: list[float], b: list[float], n: int = 8) -> dict[int, dict[str, float]]:
    mean_a = sum(a) / len(a)
    mean_b = sum(b) / len(b)
    hann = [0.5 - 0.5 * math.cos(2.0 * math.pi * i / (n - 1)) for i in range(n)]
    wa = [(a[y * n + x] - mean_a) * hann[x] * hann[y] for y in range(n) for x in range(n)]
    wb = [(b[y * n + x] - mean_b) * hann[x] * hann[y] for y in range(n) for x in range(n)]

    def dft(values: list[float], kx: int, ky: int) -> complex:
        total = 0j
        for y in range(n):
            for x in range(n):
                phase = -2.0j * math.pi * (kx * x + ky * y) / n
                total += values[y * n + x] * cmath.exp(phase)
        return total

    rings = {
        r: {"count": 0.0, "cross": 0.0, "power_a": 0.0, "power_b": 0.0}
        for r in range(1, n // 2 + 1)
    }
    for iy in range(n):
        ky = iy if iy <= n // 2 else iy - n
        for ix in range(n):
            kx = ix if ix <= n // 2 else ix - n
            radius = int(math.floor(math.hypot(kx, ky) + 0.5))
            if radius == 0 or radius > n // 2:
                continue
            av = dft(wa, ix, iy)
            bv = dft(wb, ix, iy)
            ring = rings[radius]
            ring["count"] += 1
            ring["cross"] += (av * bv.conjugate()).real
            ring["power_a"] += abs(av) ** 2
            ring["power_b"] += abs(bv) ** 2
    return rings


def parse_probe(text: str) -> dict[int, dict[str, float]]:
    lines = [line for line in text.splitlines() if re.match(r"^\d+,", line)]
    rows = csv.DictReader(
        io.StringIO("radius,count,cross,power_a,power_b\n" + "\n".join(lines))
    )
    parsed: dict[int, dict[str, float]] = {}
    for row in rows:
        radius = int(row["radius"])
        parsed[radius] = {
            "count": float(row["count"]),
            "cross": float(row["cross"]),
            "power_a": float(row["power_a"]),
            "power_b": float(row["power_b"]),
        }
    if len(parsed) != 4:
        raise RuntimeError(f"Rust probe yielded {len(parsed)} rings, expected 4\n{text}")
    return parsed


def main() -> int:
    clean_cmd = [
        "cargo",
        "test",
        "-p",
        "strehl-core",
        "split::tests",
        "--",
        "--nocapture",
        "--test-threads=1",
    ]
    clean_code, clean_text = run(clean_cmd)
    if clean_code != 0:
        print(clean_text)
        raise RuntimeError(f"clean controls returned {clean_code}, expected 0")

    plants: dict[str, int] = {}
    for plant in ("N1", "P1", "S1", "C1"):
        code, text = run(
            [
                "cargo",
                "test",
                "-p",
                "strehl-core",
                "split::tests::commission_acceptance",
                "--",
                "--exact",
                "--nocapture",
                "--test-threads=1",
            ],
            plant,
        )
        plants[plant] = code
        if code != 101:
            print(text)
            raise RuntimeError(f"{plant} returned {code}, expected planted RED code 101")

    probe_code, probe_text = run(
        ["cargo", "run", "-p", "strehl-core", "--example", "split-probe"]
    )
    if probe_code != 0:
        print(probe_text)
        raise RuntimeError(f"Rust fixed-array probe returned {probe_code}")
    rust = parse_probe(probe_text)
    a, b = fixed_planes()
    reference = direct_dft_rings(a, b)
    max_relative_error = 0.0
    for radius in reference:
        for field in ("count", "cross", "power_a", "power_b"):
            got = rust[radius][field]
            want = reference[radius][field]
            error = abs(got - want) / max(1.0, abs(want))
            max_relative_error = max(max_relative_error, error)
            if error > 1e-9:
                raise RuntimeError(
                    f"DFT mismatch ring={radius} field={field}: "
                    f"Rust={got:.17e}, Python={want:.17e}, rel={error:.3e}"
                )

    readings = {}
    for key in ("NULL", "COMMON_MODE", "POSITIVE", "SHARPEN", "CENSOR"):
        match = re.search(rf"{key} [^\r\n]*", clean_text)
        if match:
            readings[key.lower()] = match.group(0)
    result = {
        "status": "COMMISSIONED_GREEN",
        "clean_exit": clean_code,
        "plants": plants,
        "all_plants_red": all(code == 101 for code in plants.values()),
        "independent_direct_dft_max_relative_error": max_relative_error,
        "readings": readings,
        "clean_command": clean_cmd,
        "probe_command": ["cargo", "run", "-p", "strehl-core", "--example", "split-probe"],
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "commission.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"COMMISSION FAILED: {exc}", file=sys.stderr)
        raise SystemExit(1)
