"""Bind a bounded synthetic operator plant to measured saved-map curvature.
No RAW/sample reads; integer guide crop rebasing preserves original CFA phase.
"""
from pathlib import Path
import hashlib,json,struct,sys
ROOT=Path(__file__).resolve().parents[4];out=Path(__file__).parent
src=ROOT/'outputs/multi-stack/completion/hdr-precision-03/alignment.json';a=json.loads(src.read_text());maps={}
for line in a['warpmap'].splitlines():
 q=line.split()
 if len(q)>=6 and q[0].isdigit() and q[1]=='placed':maps[int(q[0])]=[struct.unpack('>d',bytes.fromhex(v))[0] for v in q[2:6]]
indices=list(range(27,34))+list(range(90,97));C=complex(3516/2,2344/2);P=complex((4201-.5)/2,(3341-.5)/2)
rows=[]
for i in indices:
 ar,ai,br,bi=maps[i];aa=complex(ar,ai);bb=(aa-1)*(P-C)+complex(br,bi)
 crop=[int(bb.real//1),int(bb.imag//1)];b=bb-complex(*crop)
 rows.append({'global_index':i,'stored_pull':maps[i],'local_pull':[ar,ai,b.real,b.imag],'removed_integer_guide_crop':crop})
second=[]
for lo in [0,7]:
 for j in range(lo+1,lo+6):second.append([rows[j+1]['local_pull'][k]-2*rows[j]['local_pull'][k]+rows[j-1]['local_pull'][k] for k in [0,1]])
result={'schema':'strehl.sr-measured-trajectory-plant.v1','command':sys.argv,'alignment_sha256':hashlib.sha256(src.read_bytes()).hexdigest(),'warpmap_sha256':a['warpmap_sha256'] if 'warpmap_sha256' in a else None,'full_geometry_quad':[3516,2344],'roi_center_sensor':[4201,3341],'rebasing':'b_local=(a-1)*(P-C)+b; remove integer guide crop per source only. Scale/rotation coefficients and CFA phase remain exact measured values. Synthetic local full geometry256x256 guide has physical fitting center256.5sensor.','scope':'Measured placements are used as known plant truth for operator tests; this does not validate their photographic accuracy. Curvature is retained, not replaced by a linear scale schedule.','second_differences_a':second,'rows':rows}
with (out/'chart-measured-trajectory-01.json').open('x') as f:json.dump(result,f,indent=2);f.write('\n')
text='// Generated by bind-chart-measured-trajectory.py; exact f64 bits, see JSON receipt.\n'
text+='pub const MEASURED: [(usize,[u64;4]);14] = [\n'
for row in rows:
 bits=[struct.unpack('>Q',struct.pack('>d',v))[0] for v in row['local_pull']]
 text+=f"    ({row['global_index']},["+','.join(f'0x{v:016x}' for v in bits)+']),\n'
text+='];\n'
with (out/'chart-measured-trajectory-01.rs').open('x') as f:f.write(text)
print(json.dumps({'alignment_sha256':result['alignment_sha256'],'max_second_difference_scale_real':max(abs(x[0]) for x in second),'max_second_difference_rotation_imag':max(abs(x[1]) for x in second),'rows':len(rows)}))
