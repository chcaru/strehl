"""FIT-only minimum-bending diagnostic, never an output geometry certificate.

The thin-plate radial basis is r^2 log(r), with the affine polynomial nullspace
and no smoothing parameter. See Bookstein (1989), doi:10.1109/34.24792, and the
SciPy RBFInterpolator mathematical documentation. This implementation is from
that mathematical definition; no external implementation source was consulted.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sys

for key in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS'):
    os.environ[key] = '1'
import numpy as np

SCALE_QUAD = 1000.0
SEED = 20261028


def kernel(a, b):
    distance_squared = np.sum((a[:, None, :] - b[None, :, :]) ** 2, axis=2)
    result = np.zeros(distance_squared.shape)
    positive = distance_squared > 0
    result[positive] = .5 * distance_squared[positive] * np.log(distance_squared[positive])
    return result


def fit(points, targets):
    normalized = np.asarray(points, dtype=float) / SCALE_QUAD
    polynomial = np.c_[np.ones(len(points)), normalized]
    if len(points) < 8 or np.linalg.matrix_rank(polynomial) < 3:
        return None
    if np.unique(points, axis=0).shape[0] != len(points):
        return None
    system = np.block([[kernel(normalized, normalized), polynomial],
                       [polynomial.T, np.zeros((3, 3))]])
    coefficients = np.linalg.solve(system, np.r_[targets, np.zeros((3, 2))])
    return normalized, coefficients


def predict(model, points):
    normalized, coefficients = model
    p = np.asarray(points) / SCALE_QUAD
    return np.c_[kernel(p, normalized), np.ones(len(p)), p] @ coefficients


def stats(errors):
    return dict(count=len(errors), rms_quad=float(np.sqrt(np.mean(errors**2))),
                median_quad=float(np.median(errors)), maximum_quad=float(errors.max()),
                within_final_half_quad=int(np.count_nonzero(errors <= .5)))


def controls():
    x, y = np.meshgrid(np.linspace(100, 3300, 17), np.linspace(100, 2100, 11))
    points = np.c_[x.ravel(), y.ravel()]
    held = (np.indices(x.shape).sum(axis=0).ravel() % 4) == 0
    # The curved field is analytic, not generated by the fitting basis.
    displacement = np.c_[32*np.sin(points[:, 0]/1500)*np.sin(points[:, 1]/1400),
                         25*np.cos(points[:, 0]/1600)*np.sin(points[:, 1]/1500)]
    targets = points + [45, -30] + displacement
    rng = np.random.default_rng(SEED)
    noisy = targets + rng.normal(0, .025, targets.shape)
    trained = fit(points[~held], noisy[~held])
    error = np.linalg.norm(predict(trained, points[held])-targets[held], axis=1)
    # Interior holdouts have actual bracketing support. Boundary extrapolation
    # is reported independently and is never declared qualified by this test.
    interior = np.all((points[held] > [100, 100]) & (points[held] < [3300, 2100]), axis=1)
    assert float(error[interior].max()) < .5
    interpolation = np.linalg.norm(predict(trained, points[~held])-noisy[~held], axis=1)
    assert float(interpolation.max()) < 1e-7
    affine_target = points @ np.array([[1.01, -.02], [.015, .99]]) + [45, -30]
    affine = fit(points[~held], affine_target[~held])
    assert np.max(np.abs(predict(affine, points)-affine_target)) < 1e-7
    poisoned = noisy.copy()
    poisoned[held] += 1000
    assert np.array_equal(trained[1], fit(points[~held], poisoned[~held])[1])
    wrong = fit(points[~held], rng.permutation(noisy[~held]))
    wrong_error = np.linalg.norm(predict(wrong, points[held])-targets[held], axis=1)
    assert float(np.sqrt(np.mean(wrong_error**2))) > 100
    # Interpolation does not make false training measurements trustworthy.
    outlier_targets = noisy.copy()
    fit_indices = np.flatnonzero(~held)
    outlier_targets[fit_indices[::13]] += [80, -50]
    outlier = fit(points[~held], outlier_targets[~held])
    outlier_error = np.linalg.norm(predict(outlier, points[held])-targets[held], axis=1)
    assert float(outlier_error.max()) > 5
    # A continuous surface cannot safely bridge a depth discontinuity.
    discontinuous = targets.copy()
    discontinuous[points[:, 0] > 1750] += [35, -25]
    depth = fit(points[~held], discontinuous[~held])
    depth_error = np.linalg.norm(predict(depth, points[held])-discontinuous[held], axis=1)
    assert float(depth_error.max()) > 5
    assert fit(np.c_[np.arange(10), np.arange(10)], np.zeros((10, 2))) is None
    duplicate = points[~held].copy()
    duplicate[1] = duplicate[0]
    assert fit(duplicate, noisy[~held]) is None
    return dict(curved_interior=stats(error[interior]), curved_all=stats(error),
                wrong_correspondence=stats(wrong_error), training_outlier=stats(outlier_error),
                depth_discontinuity=stats(depth_error), exact_affine=True,
                heldout_poisoning_leaves_training_exact=True, degenerate_design_refused=True,
                no_training_outlier_robustness_claim=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    result = dict(schema='strehl.mosaic-local-interpolant-controls.v1', command=sys.argv,
                  source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  scale_quad=SCALE_QUAD, smoothing=0, controls=controls(),
                  claim='Mechanical commissioning only. All real heldouts and loops remain independent final gates; no photograph, calibrated point variance, or real surface claim.')
    with args.out.open('x') as stream:
        json.dump(result, stream, indent=2)
        stream.write('\n')
    print(json.dumps(result, indent=2))
