r"""M75 step 4 -- mechanism follow-up.  Committed before running.

Three gaps left by src/03-criteria.py, all answerable from data already on disk:

F1  The COLUMN trends in O5 have no noise floor.  O5 reported them; nothing
    established which are real.  N_grad and N_indep, column arm.

F2  ROW versus COLUMN organisation, each statistic normalised by its own floor.
    Discipline 473: a mechanism is located by where the noise is GENERATED.  If
    the alpha gradient is row-organised and the covariance column-organised
    they are generated by different circuits, and that is a second separator
    independent of K3.

F3  ADDITIVE versus MULTIPLICATIVE, the test K5 opens.  K5 found the GREENS
    carry the gradient.  Two mechanisms produce that:

      ADDITIVE   an extra input-referred noise power that varies with row --
                 dark-current shot noise being the obvious candidate, since
                 var_e = mean_e for a Poisson process.  This adds the SAME
                 number of e^2 to alpha_low and to alpha_high, because both are
                 input-referred and dark current does not know which gain mode
                 the chip is in.  PREDICTION: delta(alpha_low) = delta(alpha_high)
                 in ABSOLUTE e^2.

      MULTIPLICATIVE  a row-dependent per-plane scale on the analog chain, the
                 same class of object as M68's B-plane 0.84x.  A scale s
                 multiplies the input-referred noise POWER by s^2 in both gain
                 modes alike.  PREDICTION: delta(alpha_low)/alpha_low =
                 delta(alpha_high)/alpha_high in FRACTION.

    The two predictions are far apart because alpha_low ~ 13 e^2 and
    alpha_high ~ 1.4 e^2, a factor of ~10.  Whichever agrees names the class of
    mechanism.  BAND: the agreeing form must agree within 3 * the N_grad floor
    of the tighter of the two trends; the losing form must fail it.  If BOTH
    agree or NEITHER does, the test does not separate and I say so.

F4  Direct dark-current check, independent of F3: trend of the mean dark signal
    per band converted to electrons, against the alpha trend.  If additive dark
    current is the mechanism, these are the same number.

Nothing here is a pre-registered gate: K0-K5 and A1-A2 are adjudicated and
their verdicts stand as reported in data/03-criteria.txt.  F1-F4 are post-hoc
mechanism work, labelled as such, and F3 carries its own failure branch.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
M72SRC = HERE.parent.parent / "M72-green-correlation" / "src"
DATA = HERE.parent / "data"


def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


m72 = _load("m72", M72SRC / "01-green-correlation.py")
m72c = _load("m72c", M72SRC / "02-criteria.py")
pre = _load("pre", HERE / "01-preregistration.py")

NBAND = pre.NBAND
PRIMARY = "k6"
SH = 400
RNG = np.random.default_rng(20250919)
OUT: list[str] = []


def say(s: str = "") -> None:
    print(s)
    OUT.append(s)


def rule(t: str) -> None:
    say("")
    say("=" * 78)
    say(t)
    say("=" * 78)


def main() -> int:
    blob = json.loads((DATA / "02-band-sweep.json").read_text(encoding="utf-8"))
    groups = sorted(blob["groups"], key=lambda g: g["iso"])
    isos = [g["iso"] for g in groups]
    g_arr = np.array([m72c.gain(i) for i in isos])
    md_arr = np.array([m72c.mode(i) for i in isos])

    def aprof(axis, plane, key):
        out = np.empty(NBAND)
        for b in range(NBAND):
            y = np.array([gg["axes"][axis][PRIMARY]["planes"][plane]["var"][b]
                          for gg in groups])
            out[b] = m72c.fit_alpha_delta(g_arr, md_arr, y)[key]
        return out

    def rprof(axis, pair, perm=False):
        out = np.empty(NBAND)
        for b in range(NBAND):
            e = [gg["axes"][axis][PRIMARY]["pairs"][pair] for gg in groups]
            c = np.mean([x["cov_perm" if perm else "cov"][b] for x in e])
            out[b] = m72.rho_from(np.mean([x["var_a"][b] for x in e]),
                                  np.mean([x["var_b"][b] for x in e]), c, True)
        return out

    # ------------------------------------------------------------------ F1 --
    rule("F1  COLUMN-ARM NOISE FLOORS  (O5 reported trends with no floor)")
    say(f"{'statistic':>10s} {'col trend':>11s} {'r':>8s} {'3*N_grad':>10s} "
        f"{'perm':>10s} {'real?':>7s}")
    colreal = {}
    for k in ("B/G2", "R/G1", "R/B", "G2/G1"):
        n, d = k.split("/")
        v = aprof("column", n, "alpha_high") / aprof("column", d, "alpha_high")
        tr, r = pre.trend(v)
        f3 = 3 * pre.ngrad_floor(v, SH, RNG)
        colreal[k] = abs(tr) > f3
        say(f"{k:>10s} {tr:>+11.4f} {r:>+8.3f} {f3:>10.5f} {'':>10s} "
            f"{'yes' if colreal[k] else 'NO':>7s}")
    for a, b, _ in m72.PAIRS:
        k = f"{a}-{b}"
        v = rprof("column", k)
        tr, r = pre.trend(v)
        f3 = 3 * pre.ngrad_floor(v, SH, RNG)
        pt = pre.trend(rprof("column", k, perm=True))[0]
        colreal[k] = abs(tr) > f3
        say(f"{k:>10s} {tr:>+11.5f} {r:>+8.3f} {f3:>10.5f} {pt:>+10.5f} "
            f"{'yes' if colreal[k] else 'NO':>7s}")

    # ------------------------------------------------------------------ F2 --
    rule("F2  ROW vs COLUMN ORGANISATION  (discipline 473)")
    say("Each trend divided by its OWN N_grad floor, so the two axes are")
    say("comparable despite different per-band pixel counts.")
    say("")
    say(f"{'statistic':>10s} {'row/floor':>11s} {'col/floor':>11s} "
        f"{'organised by':>14s}")
    rows = []
    for k in ("B/G2", "R/G1", "G2/G1"):
        n, d = k.split("/")
        rv = aprof("row", n, "alpha_high") / aprof("row", d, "alpha_high")
        cv = aprof("column", n, "alpha_high") / aprof("column", d, "alpha_high")
        rows.append((k, abs(pre.trend(rv)[0]) / pre.ngrad_floor(rv, SH, RNG),
                     abs(pre.trend(cv)[0]) / pre.ngrad_floor(cv, SH, RNG)))
    for p in m72.PLANES:
        rv = aprof("row", p, "alpha_high")
        rv = rv / rv.mean()
        cv = aprof("column", p, "alpha_high")
        cv = cv / cv.mean()
        rows.append((f"alpha_{p}", abs(pre.trend(rv)[0]) / pre.ngrad_floor(rv, SH, RNG),
                     abs(pre.trend(cv)[0]) / pre.ngrad_floor(cv, SH, RNG)))
    for a, b, _ in m72.PAIRS:
        k = f"{a}-{b}"
        rv, cv = rprof("row", k), rprof("column", k)
        rows.append((k, abs(pre.trend(rv)[0]) / pre.ngrad_floor(rv, SH, RNG),
                     abs(pre.trend(cv)[0]) / pre.ngrad_floor(cv, SH, RNG)))
    for k, rr, cc in rows:
        lab = "row" if rr > 3 and cc <= 3 else (
            "column" if cc > 3 and rr <= 3 else (
                "both" if rr > 3 and cc > 3 else "neither"))
        say(f"{k:>10s} {rr:>11.1f} {cc:>11.1f} {lab:>14s}")

    # ------------------------------------------------------------------ F3 --
    rule("F3  ADDITIVE vs MULTIPLICATIVE  (the test K5 opens)")
    say("ADDITIVE (e.g. dark-current shot noise): d(alpha_low) = d(alpha_high)")
    say("                                          in ABSOLUTE e^2.")
    say("MULTIPLICATIVE (a row-dependent per-plane analog scale, the same class")
    say("  of object as M68's B-plane 0.84x): equal in FRACTION.")
    say("")
    say(f"{'plane':>6s} {'a_low':>9s} {'a_high':>9s} {'d_low':>10s} "
        f"{'d_high':>10s} {'abs ratio':>10s} {'frac_low':>9s} {'frac_high':>10s} "
        f"{'frac ratio':>11s}")
    frac_ok, abs_ok = {}, {}
    for p in m72.PLANES:
        lo, hi = aprof("row", p, "alpha_low"), aprof("row", p, "alpha_high")
        dlo, dhi = pre.trend(lo)[0], pre.trend(hi)[0]
        flo, fhi = dlo / lo.mean(), dhi / hi.mean()
        f_lo = pre.ngrad_floor(lo / lo.mean(), SH, RNG)
        f_hi = pre.ngrad_floor(hi / hi.mean(), SH, RNG)
        tight = min(f_lo, f_hi)
        frac_ok[p] = abs(flo - fhi) < 3 * tight
        abs_ok[p] = abs(dlo - dhi) < 3 * tight * min(lo.mean(), hi.mean())
        say(f"{p:>6s} {lo.mean():>9.4f} {hi.mean():>9.4f} {dlo:>+10.4f} "
            f"{dhi:>+10.4f} {dlo/dhi if dhi else float('nan'):>10.2f} "
            f"{flo:>+9.4f} {fhi:>+10.4f} {flo/fhi if fhi else float('nan'):>11.2f}")
    say("")
    say("verdict per plane (greens are the ones carrying the gradient):")
    for p in ("G1", "G2"):
        if frac_ok[p] and not abs_ok[p]:
            v = "MULTIPLICATIVE -- a row-dependent per-plane analog scale"
        elif abs_ok[p] and not frac_ok[p]:
            v = "ADDITIVE -- an extra input-referred noise power"
        elif abs_ok[p] and frac_ok[p]:
            v = "BOTH agree -- F3 does NOT separate them"
        else:
            v = "NEITHER agrees -- F3 does NOT separate them"
        say(f"  {p}: {v}")

    # ------------------------------------------------------------------ F4 --
    rule("F4  DIRECT DARK-CURRENT CHECK  (independent of F3)")
    say("If the gradient is dark-current shot noise, the rise in alpha (e^2)")
    say("equals the rise in mean dark signal (e), since var_e = mean_e.")
    say("")
    say(f"{'plane':>6s} {'d_alpha_high':>13s} {'d_alpha_low':>12s} "
        f"{'d_dark_e':>10s} {'dark r':>8s} {'shape':>10s}")
    for p in m72.PLANES:
        de = np.zeros(NBAND)
        for gi, gg in enumerate(groups):
            e = gg["axes"]["row"][PRIMARY]["planes"][p]
            mdn = np.array(e["mean_dn"], float) / np.array(e["n"], float)
            de += mdn / m72c.gain(isos[gi])
        de /= len(groups)
        tr, r = pre.trend(de)
        mid = de[NBAND // 4: 3 * NBAND // 4].mean()
        edge = 0.5 * (de[: NBAND // 8].mean() + de[-NBAND // 8:].mean())
        shape = "U-shaped" if edge > mid else "monotone"
        hi = aprof("row", p, "alpha_high")
        lo = aprof("row", p, "alpha_low")
        say(f"{p:>6s} {pre.trend(hi)[0]:>+13.4f} {pre.trend(lo)[0]:>+12.4f} "
            f"{tr:>+10.4f} {r:>+8.3f} {shape:>10s}")
    say("")
    say("green alpha_high row profile (normalised), 32 bands, top to bottom:")
    for p in ("G1", "G2", "R", "B"):
        v = aprof("row", p, "alpha_high")
        v = v / v.mean()
        say(f"  {p:>3s} " + " ".join(f"{x:.3f}" for x in v[::2]))

    # ------------------------------------------------------------------ F5 --
    rule("F5  UPSTREAM SHARE AT BOTH ENDS  (O4 quoted only the low-ISO share)")
    gs = (m72c.gain(isos[-1]) / m72c.gain(isos[0])) ** 2
    say(f"G^2 ratio ISO {isos[0]} -> {isos[-1]}: {gs:.1f}")
    say(f"{'pair':>7s} {'class':>9s} {'f @ISO50':>10s} {'f @ISO2000':>12s}")
    for a, b, cls in m72.PAIRS:
        k = f"{a}-{b}"
        c0 = np.average(groups[0]["axes"]["row"][PRIMARY]["pairs"][k]["cov"],
                        weights=groups[0]["axes"]["row"][PRIMARY]["pairs"][k]["n"])
        c1 = np.average(groups[-1]["axes"]["row"][PRIMARY]["pairs"][k]["cov"],
                        weights=groups[-1]["axes"]["row"][PRIMARY]["pairs"][k]["n"])
        f0 = (c1 / c0 - 1.0) / (gs - 1.0)
        f1 = f0 * gs / (f0 * gs + (1 - f0))
        say(f"{k:>7s} {cls:>9s} {f0:>10.4f} {f1:>12.4f}")

    (DATA / "04-mechanism.txt").write_text("\n".join(OUT) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
