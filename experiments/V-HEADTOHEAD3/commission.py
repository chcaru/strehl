class Record:
    def __init__(self) -> None:
        self.controls = 0
        self.control_failures = 0
        self.plants = 0
        self.plant_failures = 0

    def control(self, name: str, passed: bool, reading: str) -> None:
        self.controls += 1
        if not passed:
            self.control_failures += 1
        print(f"CONTROL {'GREEN' if passed else 'FAIL ':5s} {name}: {reading}")

    def plant(self, name: str, went_red: bool, reading: str) -> None:
        self.plants += 1
        if not went_red:
            self.plant_failures += 1
        print(f"PLANT   {'RED' if went_red else 'MISS':5s} {name}: {reading}")

    def finish(self) -> int:
        ok = self.control_failures == 0 and self.plant_failures == 0
        print(
            "COMMISSION "
            f"{'GREEN' if ok else 'FAILED'}: "
            f"{self.controls - self.control_failures}/{self.controls} controls GREEN; "
            f"{self.plants - self.plant_failures}/{self.plants} plants RED"
        )
        return 0 if ok else 1


def normalise(x: np.ndarray) -> np.ndarray:
    y = np.asarray(x, np.float64)
    return (y - np.min(y)) / (np.max(y) - np.min(y))


def fixture(n: int = 384, seed: int = 709) -> np.ndarray:
    """Fixed 1/f texture, three gratings, and independently placed edges."""
    rng = np.random.default_rng(seed)
    fy = np.fft.fftfreq(n)[:, None]
    fx = np.fft.fftfreq(n)[None, :]
    radius = np.sqrt(fx * fx + fy * fy)
    phase = np.exp(2j * np.pi * rng.random((n, n)))
    amp = 1.0 / np.maximum(radius, 1.0 / n)
    texture = np.fft.ifft2(amp * phase).real
    texture = (texture - texture.mean()) / texture.std()
    yy, xx = np.mgrid[:n, :n]
    gratings = (
        0.32 * np.sin(2 * np.pi * 0.18 * xx + 0.3)
        + 0.22 * np.sin(2 * np.pi * 0.27 * (0.8 * xx + 0.6 * yy) + 1.1)
        + 0.15 * np.sin(2 * np.pi * 0.35 * yy + 0.7)
    )
    edges = 0.35 * (xx > n * 0.37) - 0.21 * (yy > n * 0.63)
    return normalise(0.25 * texture + gratings + edges)


def tone_transforms(x: np.ndarray) -> dict[str, np.ndarray]:
    z = normalise(x)
    return {
        "affine": 0.17 + 2.3 * z,
        "gamma3": z**3,
        "logistic12": 1.0 / (1.0 + np.exp(-12.0 * (z - 0.5))),
    }


def rank_oracle(rec: Record) -> None:
    x = np.array(
        [
            [4, 1, 1, 9],
            [3, 7, 5, 5],
            [8, 2, 6, 0],
            [10, 12, 11, 13],
        ],
        dtype=np.float64,
    )
    # Written from the sorted values, not generated by rankdata:
    expected_ranks = np.array(
        [
            [6, 2.5, 2.5, 12],
            [5, 10, 7.5, 7.5],
            [11, 4, 9, 1],
            [13, 15, 14, 16],
        ],
        dtype=np.float64,
    )
    expected = (expected_ranks - 8.5) / 16.0
    actual = midrank_field(x)
    err = float(np.max(np.abs(actual - expected)))
    rec.control("external 4x4 mid-rank oracle", err == 0.0, f"max error {err:.3g}")
    sabotaged = expected.copy()
    sabotaged[0, 0], sabotaged[1, 0] = sabotaged[1, 0], sabotaged[0, 0]
    bad_err = float(np.max(np.abs(actual - sabotaged)))
    rec.plant(
        "permuted external ranks",
        bad_err != 0.0,
        f"planted max error {bad_err:.6f}",
    )


def tone_controls(rec: Record, x: np.ndarray, prefix: str) -> None:
    base = ordinal_shares(x)
    worst = 0.0
    readings = []
    for name, y in tone_transforms(x).items():
        moved = float(np.max(np.abs(ordinal_shares(y) - base)))
        worst = max(worst, moved)
        readings.append(f"{name}={moved:.3e}")
    rec.control(
        f"{prefix} strict-tone invariance",
        worst <= 1e-10,
        "max |delta A| " + ", ".join(readings),
    )

    raw_base = raw_shares(x)
    raw_moves = []
    for name, y in tone_transforms(x).items():
        raw_moves.append(
            (name, float(np.max(np.abs(raw_shares(y) / raw_base - 1.0))))
        )
    raw_worst = max(v for _, v in raw_moves)
    rec.control(
        f"{prefix} tone-plant potency",
        raw_worst >= 0.05,
        "raw max relative move "
        + ", ".join(f"{name}={value:.3f}" for name, value in raw_moves),
    )
    rec.plant(
        f"{prefix} raw-share substitution",
        raw_worst >= 0.05 and worst <= 1e-10,
        f"raw moves {raw_worst:.3f}, ordinal moves {worst:.3e}",
    )

    z = normalise(x)
    solar = np.where(z < 0.5, z, 1.0 - z)
    solar_move = float(np.max(np.abs(ordinal_shares(solar) / base - 1.0)))
    rec.control(
        f"{prefix} non-monotone potency",
        solar_move >= 0.05,
        f"solarise max relative move {solar_move:.3f}",
    )
    rec.plant(
        f"{prefix} blind constant gauge",
        not (0.0 >= 0.05),
        "blind statistic move 0.000 cannot detect solarisation",
    )


def synthetic_ratio_tone_control(rec: Record) -> None:
    originals = []
    transformed: dict[str, list[np.ndarray]] = {
        name: [] for name in tone_transforms(fixture(192)).keys()
    }
    for seed in range(8):
        s = fixture(192, seed=2000 + seed)
        c = ndimage.gaussian_filter(s, 0.45)
        ss = ordinal_shares(s)
        originals.append(np.log(ss / ordinal_shares(c)))
        for name, toned in tone_transforms(c).items():
            transformed[name].append(np.log(ss / ordinal_shares(toned)))
    base = np.exp(np.mean(np.asarray(originals), axis=0))
    moves = {
        name: float(
            np.max(
                np.abs(
                    np.exp(np.mean(np.asarray(rows), axis=0))
                    - base
                )
            )
        )
        for name, rows in transformed.items()
    }
    worst = max(moves.values())
    rec.control(
        "synthetic paired R_detail tone invariance",
        worst <= 1e-10,
        ", ".join(f"{name}={value:.3e}" for name, value in moves.items()),
    )


def registration_controls(rec: Record) -> None:
    rng = np.random.default_rng(181)
    source = rng.normal(size=(160, 160))
    source += ndimage.gaussian_filter(rng.normal(size=source.shape), 4.0)
    shifts = ((0, 0), (1, 0), (0, -1), (2, 3), (-3, 2), (5, -5))
    recovered = []
    equality = []
    for planted in shifts:
        moving = np.roll(source, planted, axis=(0, 1))
        dy, dx, peak = phase_correction(source, moving, max_shift=12)
        expected = (-planted[0], -planted[1])
        a, b = overlap_after_shift(source, moving, (dy, dx))
        same = bool(np.array_equal(a, b))
        ok = (dy, dx) == expected and same
        recovered.append(((dy, dx), peak))
        equality.append(same)
        rec.control(
            f"shift {planted} correction",
            ok,
            f"expected {expected}, got {(dy, dx)}, direct equality={same}, peak={peak:.6f}",
        )

    planted = (2, 3)
    moving = np.roll(source, planted, axis=(0, 1))
    right = phase_correction(source, moving, max_shift=12)[:2]
    wrong = (-right[0], -right[1])
    ar, br = overlap_after_shift(source, moving, wrong)
    rec.plant(
        "registration wrong sign",
        not np.array_equal(ar, br),
        f"wrong correction {wrong} fails fixed source equality",
    )
    an, bn = overlap_after_shift(source, moving, (0, 0))
    rec.plant(
        "registration no-op",
        not np.array_equal(an, bn),
        "zero correction fails fixed source equality",
    )


def synthetic_scale_pair(scale: float, n: int = 512) -> tuple[np.ndarray, np.ndarray]:
    s = fixture(n, seed=991)
    c = ndimage.zoom(s, 1.0 / scale, order=1, mode="reflect", prefilter=False)
    return midrank_field(s), midrank_field(c)


def best_scale(
    sr: np.ndarray, cr: np.ndarray, scales: np.ndarray
) -> tuple[float, bool, list[float]]:
    scores = [_scale_score(sr, cr, float(s), tile=96, ntile=4)[0] for s in scales]
    idx = int(np.argmax(scores))
    return float(scales[idx]), 0 < idx < len(scales) - 1, scores


def scale_controls(rec: Record) -> None:
    for truth in (0.970, 1.035):
        sr, cr = synthetic_scale_pair(truth)
        scales = np.arange(truth - 0.015, truth + 0.0151, 0.001)
        estimate, interior, _ = best_scale(sr, cr, scales)
        rec.control(
            f"known scale {truth:.3f}",
            interior and abs(estimate - truth) <= 0.003,
            f"estimate {estimate:.3f}, error {estimate-truth:+.3f}, interior={interior}",
        )
    truth = 1.035
    sr, cr = synthetic_scale_pair(truth)
    bad_range = np.arange(0.970, 1.001, 0.002)
    estimate, interior, _ = best_scale(sr, cr, bad_range)
    rec.plant(
        "scale outside forced range",
        not interior,
        f"estimate {estimate:.3f}, interior={interior}",
    )


def blur_controls(rec: Record) -> list[float]:
    x = fixture()
    sigmas = (0.0, 0.5, 1.0, 2.0)
    shares = np.asarray(
        [ordinal_shares(ndimage.gaussian_filter(x, s)) for s in sigmas]
    )
    fine = np.sum(shares[:, 3:], axis=1)
    monotone = bool(np.all(np.diff(fine) < 0))
    reach = float(1.0 - fine[-1] / fine[0])
    rec.control(
        "blur ladder fine-band reach",
        monotone and reach >= 0.15,
        f"fine shares {fine.tolist()}, reach={reach:.3f}, monotone={monotone}",
    )
    disabled = np.asarray([ordinal_shares(x) for _ in sigmas])
    disabled_reach = float(
        1.0 - np.sum(disabled[-1, 3:]) / np.sum(disabled[0, 3:])
    )
    rec.plant(
        "disabled blur",
        disabled_reach < 0.15,
        f"reach {disabled_reach:.3f} fails 0.15 gate",
    )
    per_band = np.abs(shares[-1] / shares[0] - 1.0)
    print(
        "BLUR SENSITIVITY "
        + ", ".join(
            f"{name}={move:.3f} {'SENSITIVE' if move >= .05 else 'NOT SENSITIVE'}"
            for name, move in zip(BAND_NAMES, per_band)
        )
    )
    return per_band.tolist()


def spatial_confound_controls(rec: Record) -> None:
    x = fixture()
    base = ordinal_shares(x)
    sharpened = x + 1.5 * (x - ndimage.gaussian_filter(x, 1.0))
    sharp = ordinal_shares(sharpened)
    sharp_gain = float(np.sum(sharp[4:]) / np.sum(base[4:]) - 1.0)
    rec.control(
        "spatial-sharpening exposure",
        sharp_gain >= 0.20,
        f"combined 0.25-0.40 share gain={sharp_gain:.3f}",
    )
    rec.plant(
        "disabled sharpening exposure",
        not (0.0 >= 0.20),
        "disabled operator gain 0.000 cannot expose upward confound",
    )

    resampled = ndimage.zoom(
        ndimage.zoom(x, 0.5, order=3, mode="reflect", prefilter=True),
        2.0,
        order=3,
        mode="reflect",
        prefilter=True,
    )
    moved = float(np.max(np.abs(ordinal_shares(resampled) / base - 1.0)))
    rec.control(
        "down-up-resampling exposure",
        moved >= 0.20,
        f"max relative band move={moved:.3f}",
    )
    rec.plant(
        "blind resampling exposure",
        not (0.0 >= 0.20),
        "blind statistic move 0.000 cannot detect down-up resampling",
    )


def flat_noise_controls(rec: Record) -> None:
    rng = np.random.default_rng(144)
    low = ndimage.gaussian_filter(rng.normal(size=(384, 384)), 12.0)
    detail = normalise(low + 0.12 * np.sin(2 * np.pi * 0.12 * np.indices(low.shape)[1]))
    flat = normalise(low)
    # Identical constant-plus-fixed-noise arms exercise the whole image
    # statistic, not just the verdict arithmetic.
    fixed_noise = np.random.default_rng(145).normal(size=flat.shape)
    flat_placebo = 0.5 + 0.01 * fixed_noise
    ds = ordinal_shares(detail)
    fs = ordinal_shares(flat_placebo)
    detail_ratio = ds / ds
    flat_ratio = fs / fs
    err = float(
        max(
            np.max(np.abs(detail_ratio - 1.0)),
            np.max(np.abs(flat_ratio - 1.0)),
        )
    )
    rec.control(
        "identical detail/flat placebo",
        err <= 1e-10,
        f"max |R_detail/R_flat-1|={err:.3e}",
    )

    # One fixed high-frequency process is added to both comparator strata.
    noise = rng.normal(size=detail.shape)
    noise -= ndimage.gaussian_filter(noise, 1.2)
    amp = 0.035
    cd = ordinal_shares(detail + amp * noise)
    flat = normalise(low)
    fs = ordinal_shares(flat)
    cf = ordinal_shares(flat + amp * noise)
    r_detail = ds / cd
    r_flat = fs / cf
    fine_unadjusted = float(np.max(np.abs(r_detail[3:] - 1.0)))
    selected = 3 + int(np.argmax(np.abs(r_detail[3:] - 1.0)))
    same_direction_veto = bool(
        (r_detail[selected] < 1 / 1.05 and r_flat[selected] < 1 / 1.05)
        or (r_detail[selected] > 1.05 and r_flat[selected] > 1.05)
    )
    rec.control(
        "shared fine-noise flat veto",
        fine_unadjusted >= 0.05 and same_direction_veto,
        f"band={BAND_NAMES[selected]}, R_detail={r_detail[selected]:.4f}, "
        f"R_flat={r_flat[selected]:.4f}, veto={same_direction_veto}",
    )
    rec.plant(
        "omit flat veto",
        same_direction_veto,
        f"unvetoed fine departure {fine_unadjusted:.3f} would be reported",
    )

    # Preserve the reading that invalidated the first preregistered estimator.
    superseded = np.exp(np.log(ds / cd) - np.log(fs / cf))
    superseded_move = float(np.max(np.abs(superseded[3:] - 1.0)))
    rec.plant(
        "superseded log subtraction",
        superseded_move > 0.05,
        f"max fine departure {superseded_move:.1f} (must remain RED)",
    )

    production = classify(
        low=0.80,
        high=0.90,
        flat_low=0.70,
        flat_high=0.80,
        sensitive=True,
    )
    rec.control(
        "production same-direction flat veto",
        production == "UNRESOLVED (FLAT VETO)",
        f"classify(...)={production}",
    )
    without_veto = "TRAILS"  # Detail CI is wholly below 1/1.05.
    rec.plant(
        "production classifier without flat veto",
        without_veto != production and without_veto == "TRAILS",
        f"mutant={without_veto}, production={production}",
    )
    precedence = robustness_downgrade(
        "NOT SENSITIVE", "UNRESOLVED (QUADRANT)", True
    )
    rec.control(
        "NOT SENSITIVE robustness precedence",
        precedence == "NOT SENSITIVE",
        f"downgrade result={precedence}",
    )
    rec.plant(
        "unconditional robustness overwrite",
        "UNRESOLVED (QUADRANT)" != precedence,
        "old unconditional assignment would overwrite NOT SENSITIVE",
    )

    structured_texture = float(np.sum(ordinal_shares(fixture())[:3]))
    white_texture = float(
        np.sum(ordinal_shares(np.random.default_rng(146).normal(size=(384, 384)))[:3])
    )
    rec.control(
        "texture-stratum direction",
        structured_texture > white_texture + 0.10,
        f"structured={structured_texture:.4f}, flat/noise={white_texture:.4f}",
    )
    rec.plant(
        "inverted texture strata",
        not (white_texture > structured_texture + 0.10),
        "selecting the lower score as detail rejects the fixed external ordering",
    )


def tie_controls(rec: Record) -> None:
    x = fixture(256)
    original = tie_census(x)
    quantised = tie_census(np.round(x * 4095.0))
    clipped_x = np.clip(x, np.quantile(x, 0.01), np.quantile(x, 0.99))
    clipped = tie_census(clipped_x)
    changed = quantised != original and clipped != original
    rec.control(
        "quantisation/clipping tie exposure",
        changed,
        f"unique/largest original={original}, q12={quantised}, clip1/99={clipped}",
    )
    rec.plant(
        "blind tie census",
        not (original == original and quantised == original and clipped == original),
        "hard-coded unchanged census would miss both plants",
    )


def hash_controls(rec: Record) -> None:
    readings = []
    all_ok = True
    actual_first = None
    expected_first = None
    for pair in PAIRS.values():
        for path, expected in (
            (pair.strehl, pair.strehl_sha256),
            (pair.comparator, pair.comparator_sha256),
        ):
            actual = sha256(path)
            readings.append(f"{path.name}={actual[:12]}")
            all_ok &= actual == expected
            if actual_first is None:
                actual_first, expected_first = actual, expected
    rec.control("four frozen file hashes", all_ok, ", ".join(readings))
    assert actual_first is not None and expected_first is not None
    sabotaged = ("0" if expected_first[0] != "0" else "1") + expected_first[1:]
    rec.plant(
        "one-nibble provenance hash",
        actual_first != sabotaged,
        f"actual {actual_first[:12]} rejects plant {sabotaged[:12]}",
    )


def real_tone_control(rec: Record, path: Path, y: int, x: int, side: int) -> None:
    import tifffile

    a = tifffile.memmap(path)
    green = np.asarray(
        a[y - side // 2 : y + side // 2, x - side // 2 : x + side // 2, 1]
    )
    if green.shape != (side, side):
        raise ValueError(f"real control crop out of bounds: {green.shape}")
    tone_controls(rec, green, f"real {path.name}@({y},{x})/{side}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--hashes", action="store_true")
    parser.add_argument("--real", action="store_true")
    parser.add_argument(
        "--real-path",
        type=Path,
        default=PAIRS["113"].strehl,
    )
    parser.add_argument("--y", type=int, default=2048)
    parser.add_argument("--x", type=int, default=3072)
    parser.add_argument("--side", type=int, default=512)
    args = parser.parse_args(argv)

    rec = Record()
    if args.hashes:
        hash_controls(rec)
    if args.real:
        real_tone_control(rec, args.real_path, args.y, args.x, args.side)
    if not args.hashes and not args.real:
        rank_oracle(rec)
        tone_controls(rec, fixture(), "synthetic")
        synthetic_ratio_tone_control(rec)
        registration_controls(rec)
        scale_controls(rec)
        blur_controls(rec)
        spatial_confound_controls(rec)
        flat_noise_controls(rec)
        tie_controls(rec)
    return rec.finish()


