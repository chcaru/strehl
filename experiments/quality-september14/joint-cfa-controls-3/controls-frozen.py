HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
OUT=HERE/"joint-cfa-controls-3"
AUTHOR=HERE/"joint-cfa.py"
EXPECTED="05fe15bece42cb44f667219c35423261358bc4b8c5b594b0c2630c545748b490"
SIZE=64
Y,X=np.mgrid[:SIZE,:SIZE]
CHANNEL=np.where((Y%2==0)&(X%2==0),0,np.where((Y%2==1)&(X%2==1),2,1)).astype(np.int32)
CORE=np.s_[8:-8,8:-8]
PHASES={"coincident":np.zeros((9,2)),"fractional2d":np.array([(x,y) for y in (-.65,0,.65) for x in (-.65,0,.65)]),
        "integer2d":np.array([(x,y) for y in (-1.,0.,1.) for x in (-1.,0.,1.)])}

def load(name,path):
    spec=importlib.util.spec_from_file_location(name,path)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);return module

def save(path,value):
    with path.open("x",encoding="utf-8") as f:
        json.dump(value,f,indent=2,allow_nan=False,default=lambda v:v.item());f.write("\n")

def scene(x,y,kind,f,orientation="oblique",blur=0.,alias_low=False):
    x=np.asarray(x,dtype=np.float64);y=np.asarray(y,dtype=np.float64)
    fx,fy=(f,0) if orientation=="x" else (.8*f,.6*f)
    if alias_low:fx,fy=-.2,0
    angle=2*np.pi*(fx*x+fy*y)+.41
    attenuation=np.exp(-2*np.pi*np.pi*blur*blur*(fx*fx+fy*fy))
    if kind=="flat":return np.broadcast_to(np.array([.32,.32,.32]),(*np.shape(x),3)).copy()
    if kind=="neutral":
        v=.35+.12*attenuation*np.cos(angle);return np.stack((v,v,v),axis=-1)
    if kind=="r-only":
        return np.stack((.35+.12*attenuation*np.cos(angle),np.full_like(x,.35),np.full_like(x,.35)),axis=-1)
    return np.stack((.42+.10*attenuation*np.cos(angle+.23),np.full_like(x,.35),
                     .29+.10*attenuation*np.sin(angle-.27)),axis=-1)

def observations(kind,f,layout,orientation="oblique",noise_seed=None,blur_mismatch=False,alias_low=False):
    xy=[];values=[];images=[];variances=[]
    rng=np.random.default_rng(noise_seed) if noise_seed is not None else None
    variance_by_channel=(.003*np.array([1.5986,1.,2.709]))**2
    for k,(dx,dy) in enumerate(PHASES[layout]):
        xx,yy=X+dx,Y+dy
        # Truth is evaluated continuously at photosite locations; never A@truth.
        rgb=scene(xx,yy,kind,f,orientation,blur=.9 if blur_mismatch and k!=4 else 0,alias_low=alias_low)
        cfa=np.take_along_axis(rgb,CHANNEL[...,None],axis=-1)[...,0].astype(np.float32)
        variance=variance_by_channel[CHANNEL].astype(np.float32)
        if rng is not None:cfa+=rng.normal(0,np.sqrt(variance),cfa.shape).astype(np.float32)
        images.append(cfa);xy.append(np.column_stack((xx.ravel(),yy.ravel())).astype(np.float64))
        values.append(cfa.ravel());variances.append(variance.ravel())
    return dict(xy=np.concatenate(xy),values=np.concatenate(values),variance=np.concatenate(variances),
        channels=np.tile(CHANNEL.ravel(),9),valid=np.ones(9*SIZE*SIZE,dtype=bool),images=images)

def metrics(rgb,truth):
    error=rgb[CORE].astype(np.float64)-truth[CORE].astype(np.float64)
    chroma=np.stack((error[...,0]-error[...,1],error[...,2]-error[...,1]),axis=-1)
    return dict(rgb_rmse=float(np.sqrt(np.mean(error**2))),chroma_rmse=float(np.sqrt(np.mean(chroma**2))),
        green_mse=float(np.mean(error[...,1]**2)),signed_bias_rgb=np.mean(error,axis=(0,1)).tolist())

def main():
    start=time.process_time();OUT.mkdir(exist_ok=False)
    assert hashlib.sha256(AUTHOR.read_bytes()).hexdigest()==EXPECTED
    # Regression for invalid run1: integer native coordinates must not truncate G.
    for kind in ("neutral","independent-colour","r-only"):
        a=scene(X,Y,kind,.2);b=scene(X.astype(np.float64),Y.astype(np.float64),kind,.2)
        assert np.array_equal(a,b)
        if kind!="neutral":assert np.all(a[...,1]==.35)
    save(OUT/"prospective-design.json",dict(scope="Native1x output only. No original RAW reads. Each observation generated by a continuous formula at its physical CFA coordinate; not the reconstruction basis.",
        shape=[SIZE,SIZE],trim=8,nominal_inputs="Neutral and independent R/B detail at frequencies .08/.20/.30; x and oblique(.8,.6) orientations; fixed phase.41. All nominal fractional2d frames share focus.",
        geometry= {k:v.tolist() for k,v in PHASES.items()},
        references="Fixed anchor-frame MHC and same-data nine-frame MHC/bilinear-gather mean; latter is a control, not an exact product render. Gather only into the running sum.",
        bars="On nominal cases, >5% AND >.0005 absolute RGB or chroma truth-RMSE increase versus same-data MHC mean blocks a broad quality claim. Flat noise is reported separately; a >5% cost must not be called a free quality gain. No data-residual/conditioning-only pass.",
        failures="Wrong maps may retain low residual while increasing truth error; blur mismatch violates the common-image model. Coincident R-only .30/- .20 alias pair has identical observations and must not be called resolved. Exact duplicated observations add no information but change the fixed data/prior balance.",
        expected_controls="Flat first. Wrong-map textured error must rise by >.002 and >25% to exercise its falsifier; flat wrong-map remains a placebo. Identical alias inputs must give identical outputs despite different native truths. No usable B data must be explicit NaN, never silently manufactured.",
        regularization="Author freezes .01*x.T*L*x first-difference prior, not squared-Laplacian. Uniform variance scaling cancels in per-channel median(variance)/variance; exact replication is not an invariance claim.",
        noise="Same independently generated Gaussian perturbations and injected per-site variances for all arms; synthetic WB-scaled sigma, not camera calibration evidence."))
    J=load("frozen_joint_cfa",AUTHOR);M=load("joint_existing_mhc",ROOT/"experiments/M95-demosaic/src/m95dem.py")
    def solve(obs):
        rgb,d=J.reconstruct((SIZE,SIZE),*[obs[k] for k in ("xy","values","variance","channels","valid")])
        expected=obs["valid"]&np.isfinite(obs["values"])&(obs["variance"]>0)&(obs["xy"][:,0]>=0)&(obs["xy"][:,1]>=0)&(obs["xy"][:,0]<SIZE-1)&(obs["xy"][:,1]<SIZE-1)
        assert np.array_equal(expected,d["used_mask"])
        summary={k:v for k,v in d.items() if not isinstance(v,np.ndarray)}
        return rgb,summary
    def compare(obs,truth,layout):
        rgb,diag=solve(obs)
        assert np.isfinite(rgb).all()
        running=np.zeros_like(rgb)
        anchor=None
        for index,((dx,dy),cfa) in enumerate(zip(PHASES[layout],obs["images"])):
            developed=M.demosaic_mhc(cfa)
            if index==4:anchor=developed.copy()
            for c in range(3):
                running[...,c]+=map_coordinates(developed[...,c],[Y-dy,X-dx],order=1,prefilter=False,mode="mirror")/np.float32(9)
        return dict(joint=metrics(rgb,truth),anchor_mhc=metrics(anchor,truth),nine_mhc_mean=metrics(running,truth),diagnostics=diag),rgb
    flats=[]
    for layout in ("coincident","fractional2d"):
        truth=scene(X,Y,"flat",0).astype(np.float32)
        for seed in (None,1001,2003):
            obs=observations("flat",0,layout,noise_seed=seed)
            row,_=compare(obs,truth,layout)
            flats.append(dict(layout=layout,noise_seed=seed,**row))
            if seed is None:assert row["joint"]["rgb_rmse"]<1e-5,"flat bias failed first"
    save(OUT/"flat-first.json",flats)
    flat_obs=observations("flat",0,"fractional2d")
    flat_rgb,_=solve(flat_obs)
    flat_wrong=dict(flat_obs);flat_wrong["xy"]=flat_obs["xy"].copy()
    for k,(dx,dy) in enumerate(PHASES["fractional2d"]):
        flat_wrong["xy"][k*SIZE*SIZE:(k+1)*SIZE*SIZE]-=np.array([2*dx,2*dy])
    flat_wrong_rgb,_=solve(flat_wrong)
    flat_placebo_delta=float(np.max(np.abs(flat_rgb[CORE]-flat_wrong_rgb[CORE])))
    assert flat_placebo_delta<1e-6,"wrong-map flat placebo failed"
    print(json.dumps(dict(flat_first=[{k:r[k] for k in ("layout","noise_seed","joint","anchor_mhc","nine_mhc_mean")} for r in flats])),flush=True)
    cases=[]
    for f in (.08,.20,.30):
        for orientation in ("x","oblique"):
            for kind in ("neutral","independent-colour"):
                truth=scene(X,Y,kind,f,orientation).astype(np.float32)
                obs=observations(kind,f,"fractional2d",orientation)
                assert np.array_equal(obs["images"][4],np.take_along_axis(truth,CHANNEL[...,None],axis=-1)[...,0])
                row,_=compare(obs,truth,"fractional2d")
                flags={key:row["joint"][key]>1.05*row["nine_mhc_mean"][key] and row["joint"][key]-row["nine_mhc_mean"][key]>.0005
                       for key in ("rgb_rmse","chroma_rmse")}
                cases.append(dict(kind=kind,frequency=f,orientation=orientation,regression_vs_same_data_mean=flags,**row))
                print(json.dumps(dict(signal={k:cases[-1][k] for k in ("kind","frequency","orientation","joint","anchor_mhc","nine_mhc_mean")})),flush=True)
    phase_rows=[]
    for layout in PHASES:
        truth=scene(X,Y,"independent-colour",.30).astype(np.float32)
        obs=observations("independent-colour",.30,layout)
        row,_=compare(obs,truth,layout)
        phase_rows.append(dict(layout=layout,**row))
    # Duplicate exactly the same observations/noise: no new geometric information.
    original=observations("independent-colour",.30,"coincident")
    original_rgb,_=solve(original)
    duplicated={k:np.concatenate((original[k],original[k])) for k in ("xy","values","variance","channels","valid")}
    dup_rgb,dup_diag=solve(duplicated)
    duplicate=dict(max_output_change=float(np.max(np.abs(dup_rgb[CORE]-original_rgb[CORE]))),
        truth_metrics=metrics(dup_rgb,scene(X,Y,"independent-colour",.30).astype(np.float32)),diagnostics=dup_diag,
        interpretation="Any change is data/prior reweighting; observations are exact duplicates and cannot establish additional resolved information.")
    alias_hi=observations("r-only",.30,"coincident","x")
    alias_lo=observations("r-only",.30,"coincident","x",alias_low=True)
    assert np.array_equal(alias_hi["values"],alias_lo["values"]),"alias pair not actually identical"
    high_rgb,_=solve(alias_hi);low_rgb,_=solve(alias_lo)
    assert np.array_equal(high_rgb,low_rgb),"same data produced a different reconstruction"
    alias=dict(high_truth=metrics(high_rgb,scene(X,Y,"r-only",.30,"x").astype(np.float32)),
        low_truth=metrics(low_rgb,scene(X,Y,"r-only",.30,"x",alias_low=True).astype(np.float32)),observations_identical=True,outputs_identical=True)
    assert max(alias["high_truth"]["rgb_rmse"],alias["low_truth"]["rgb_rmse"])>.02,"alias falsifier lacks power"
    # Wrong-map/blur failure stimuli, generated independently of solver A.
    correct=observations("independent-colour",.30,"fractional2d")
    truth=scene(X,Y,"independent-colour",.30).astype(np.float32)
    correct_rgb,correct_diag=solve(correct)
    wrong=dict(correct);wrong["xy"]=correct["xy"].copy()
    for k,(dx,dy) in enumerate(PHASES["fractional2d"]):wrong["xy"][k*SIZE*SIZE:(k+1)*SIZE*SIZE]-=np.array([2*dx,2*dy])
    wrong_rgb,wrong_diag=solve(wrong)
    blurred=observations("independent-colour",.30,"fractional2d",blur_mismatch=True)
    blur_rgb,blur_diag=solve(blurred)
    mismatch=dict(correct=metrics(correct_rgb,truth),wrong_map=metrics(wrong_rgb,truth),blur_mismatch=metrics(blur_rgb,truth),
        diagnostics=dict(correct=correct_diag,wrong_map=wrong_diag,blur_mismatch=blur_diag))
    mismatch["wrong_map_falsifier_exercised"]=mismatch["wrong_map"]["rgb_rmse"]>max(mismatch["correct"]["rgb_rmse"]*1.25,mismatch["correct"]["rgb_rmse"]+.002)
    no_blue=dict(correct);no_blue["valid"]=correct["valid"]&(correct["channels"]!=2)
    absent,absent_diag=solve(no_blue)
    assert np.isnan(absent[...,2]).all() and absent_diag["channels"][2]["status"]=="NO_USABLE_OBSERVATIONS"
    failures=[{k:r[k] for k in ("kind","frequency","orientation","regression_vs_same_data_mean")} for r in cases if any(r["regression_vs_same_data_mean"].values())]
    assert hashlib.sha256(AUTHOR.read_bytes()).hexdigest()==EXPECTED
    save(OUT/"result.json",dict(status="CONTINUOUS_CFA_FALSIFIERS_EXECUTED",nominal_cases=cases,nominal_bar_failures=failures,
        phase_cases=phase_rows,exact_duplication=duplicate,coincident_alias=alias,mismatch=mismatch,
        unsupported_channel_check=absent_diag,wrong_map_flat_placebo_max_delta=flat_placebo_delta,
        fixture_regression="Integer and f64 coordinates agree; constant G=.35; reference CFA sites equal native truth in all 12 nominal cases.",
        cpu_seconds=time.process_time()-start,source_sha256=EXPECTED))
    print(json.dumps(dict(nominal_failures=len(failures),wrong_map_falsifier_exercised=mismatch["wrong_map_falsifier_exercised"],
        correct=mismatch["correct"],wrong_map=mismatch["wrong_map"],blur_mismatch=mismatch["blur_mismatch"],cpu_seconds=time.process_time()-start)))

if __name__=="__main__":main()
