    #[test]
    fn the_teleconverter_changes_the_lens_id_and_two_bytes_is_the_whole_difference() {
        // The red control, in code: the same fixture with the bare-lens id.
        // Measured on a real file too -- a two-byte edit of a scratch copy of
        // bee-3-cpl/DSC00299.ARW moved exiftool from
        // "Sony FE 100mm F2.8 Macro GM OSS + 2X Teleconverter" to
        // "Sony FE 100mm F2.8 Macro GM OSS", and this parser with it.
        let with_tc = Builder::default();
        let bare = Builder {
            lens_type3: Some(32893),
            ..Builder::default()
        };
        let a = with_tc.build();
        let b = bare.build();
        assert_eq!(a.len(), b.len());
        let differing = a.iter().zip(&b).filter(|(x, y)| x != y).count();
        assert_eq!(differing, 2, "the id is the only thing that moved");

        assert_eq!(with_tc.identity().lens_type3, Some(33094));
        assert_eq!(bare.identity().lens_type3, Some(32893));
        assert_eq!(
            with_tc.identity().same_gear_as(&bare.identity()),
            Some(false),
            "a teleconverted capture is not the same optical path as a bare one"
        );
    }

