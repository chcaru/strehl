    #[test]
    fn a_missing_lens_id_is_unknown_and_never_a_match() {
        // The whole point of the three-valued answer: "I cannot tell" must not
        // read as "yes" (a wrong profile at full strength) and must be
        // distinguishable from "no".
        let unknown = Builder {
            lens_type3: None,
            ..Builder::default()
        }
        .identity();
        let known = Builder::default().identity();
        assert_eq!(unknown.lens_type3, None);
        assert_eq!(known.same_gear_as(&unknown), None);
        assert_eq!(unknown.same_gear_as(&known), None);
        assert_eq!(unknown.same_gear_as(&unknown), None);
        // ...and it is not the empty identity either: it knows the body.
        assert!(!unknown.is_empty());
        assert_eq!(unknown.model.as_deref(), Some("ILCE-7CM2"));
    }

