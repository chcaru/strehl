#!/usr/bin/env python3
"""Reproduce Strehl's vector master, PNGs and Windows ICO using Python stdlib.

Run with --check to compare every generated byte without modifying assets.
The Rust build consumes checked-in assets and never needs Python.
"""
from pathlib import Path
import argparse
import math
import struct
import sys
import zlib

ROOT = Path(__file__).resolve().parent
SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)
# Sunset: a disc cut into horizontal planes. The plane in focus is the solid gold
# cap; the planes below it thin out and darken as they fall away from focus.
INKS = ("#e6b450", "#e0893e", "#cc5a33", "#a23f2c", "#74372a", "#74372a")
# The vector master in a 64-unit frame: a disc of radius 30 about (32, 32), and
# the top and bottom edge of each plane.
RADIUS = 30
BANDS = ((2, 27.75), (29.75, 35.25), (38, 42.25), (46, 49.25), (53.5, 55.75), (60.5, 62))
# Up to 48 px the planes are fitted by hand to whole pixel rows, because rounding
# the master merges planes or leaves smudges: the disc radius, then each plane's
# first row and the row after its last. Every gap keeps at least one pixel.
FITTED = {
    16: (8, ((0, 7), (8, 10), (11, 12), (13, 14), (15, 16))),
    20: (10, ((0, 9), (10, 12), (13, 14), (16, 17), (19, 20))),
    24: (12, ((0, 10), (11, 13), (14, 16), (17, 18), (20, 21), (23, 24))),
    32: (15, ((1, 14), (15, 18), (19, 21), (23, 25), (27, 28), (30, 31))),
    40: (19, ((1, 17), (19, 22), (24, 26), (29, 31), (34, 35), (38, 39))),
    48: (23, ((1, 21), (23, 27), (29, 32), (35, 37), (40, 42), (46, 47))),
}


def color(hex_value):
    return tuple(bytes.fromhex(hex_value.removeprefix("#"))) + (255,)


def layout(size):
    """The disc radius and each plane's pixel rows at one icon size."""
    if size in FITTED:
        return FITTED[size]
    factor = size / 64
    snap = lambda value: math.floor(value * factor + 0.5)
    return RADIUS * factor, tuple((snap(top), snap(bottom)) for top, bottom in BANDS)


class Image:
    def __init__(self, width, height=None, background=(0, 0, 0, 0)):
        self.width = width
        self.height = height or width
        self.pixels = bytearray(bytes(background) * (self.width * self.height))

    def getpixel(self, point):
        x, y = point
        offset = (y * self.width + x) * 4
        return self.pixels[offset:offset + 4]

    def span(self, y, left, right, ink):
        left = max(0, math.ceil(left - 0.5))
        right = min(self.width, math.ceil(right - 0.5))
        if 0 <= y < self.height and left < right:
            offset = (y * self.width + left) * 4
            self.pixels[offset:offset + (right - left) * 4] = bytes(ink) * (right - left)

    def paste(self, image, left, top):
        for y in range(image.height):
            for x in range(image.width):
                r, g, b, a = image.getpixel((x, y))
                offset = ((y + top) * self.width + x + left) * 4
                for channel, value in enumerate((r, g, b)):
                    self.pixels[offset + channel] = (value * a + self.pixels[offset + channel] * (255 - a) + 127) // 255
                self.pixels[offset + 3] = 255


def render(size):
    """Every plane starts and ends on a pixel row, so only the disc edge needs
    coverage. Each pixel keeps its plane's full colour and carries the disc's
    coverage as alpha: no dark fringe on light desktops or light fringe on dark."""
    radius, planes = layout(size)
    centre = size / 2
    result = Image(size)
    steps = 16
    for index, (top, bottom) in enumerate(planes):
        ink = color(INKS[index])[:3]
        for y in range(top, bottom):
            cover = [0.0] * size
            for step in range(steps):
                dy = y + (step + 0.5) / steps - centre
                if abs(dy) >= radius:
                    continue
                half = math.sqrt(radius * radius - dy * dy)
                left, right = centre - half, centre + half
                for x in range(max(0, math.floor(left)), min(size, math.ceil(right))):
                    cover[x] += max(0.0, min(x + 1, right) - max(x, left)) / steps
            for x, amount in enumerate(cover):
                alpha = round(255 * min(1.0, amount))
                if alpha:
                    at = (y * size + x) * 4
                    result.pixels[at:at + 4] = bytes(ink + (alpha,))
    return result


def png(image):
    def chunk(kind, payload):
        return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload))
    rows = b"".join(b"\0" + image.pixels[y * image.width * 4:(y + 1) * image.width * 4]
                    for y in range(image.height))
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", image.width, image.height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def dib(image):
    """32-bit BGRA + AND mask for native small Windows icon frames."""
    size = image.width
    rows = []
    masks = []
    stride = ((size + 31) // 32) * 4
    for y in reversed(range(size)):
        row = bytearray()
        mask = bytearray(stride)
        for x in range(size):
            r, g, b, a = image.getpixel((x, y))
            row.extend((b, g, r, a))
            if a == 0:
                mask[x // 8] |= 0x80 >> (x % 8)
        rows.append(row)
        masks.append(mask)
    pixels = b"".join(rows)
    header = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, len(pixels), 0, 0, 0, 0)
    return header + pixels + b"".join(masks)


def ico(images):
    frames = [dib(image) if image.width <= 48 else png(image) for image in images]
    offset = 6 + 16 * len(frames)
    entries = []
    for size, payload in zip(SIZES, frames):
        entries.append(struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32, len(payload), offset))
        offset += len(payload)
    return struct.pack("<HHH", 0, 1, len(frames)) + b"".join(entries) + b"".join(frames)


def svg():
    shapes = [f'    <rect x="2" y="{top}" width="60" height="{bottom - top}" fill="{ink}"/>'
              for (top, bottom), ink in zip(BANDS, INKS)]
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">\n'
            '  <title>Strehl: the plane in focus, and the stack falling away below it</title>\n'
            f'  <clipPath id="disc"><circle cx="32" cy="32" r="{RADIUS}"/></clipPath>\n'
            '  <g clip-path="url(#disc)">\n' + "\n".join(shapes) + "\n  </g>\n</svg>\n").encode()


def preview(images):
    sheet = Image(720, 260, color("#111112"))
    digits = {
        "0": (7, 5, 5, 5, 7), "1": (2, 6, 2, 2, 7), "2": (7, 1, 7, 4, 7),
        "3": (7, 1, 7, 1, 7), "4": (5, 5, 7, 1, 1), "5": (7, 4, 7, 1, 7),
        "6": (7, 4, 7, 5, 7), "7": (7, 1, 2, 2, 2), "8": (7, 5, 7, 5, 7),
    }
    for row, background in enumerate(("#111112", "#ededeb")):
        for y in range(row * 130, (row + 1) * 130):
            sheet.span(y, 0, 720, color(background))
        x = 20
        for image in images[:7]:
            sheet.paste(image, x, row * 130 + 28)
            for column, digit in enumerate(str(image.width)):
                for y, bits in enumerate(digits[digit]):
                    for bit in range(3):
                        if bits & (1 << (2 - bit)):
                            at = x + column * 5 + bit
                            sheet.span(row * 130 + 104 + y, at, at + 1, color("#a18a5f"))
            x += image.width + 25
        sheet.paste(images[-2], 580, row * 130 + 1)
    return png(sheet)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    images = [render(size) for size in SIZES]
    files = {"strehl.svg": svg(), "strehl.ico": ico(images), "icon-preview.png": preview(images)}
    files.update({f"strehl-{image.width}.png": png(image) for image in images})
    failed = []
    for name, data in files.items():
        path = ROOT / name
        if options.check:
            if not path.is_file() or path.read_bytes() != data:
                failed.append(name)
        else:
            path.write_bytes(data)
    if failed:
        sys.exit("Icon assets differ: " + ", ".join(failed))
    print(f"{'Verified' if options.check else 'Generated'} {len(files)} icon assets; {len(SIZES)} Windows sizes.")


if __name__ == "__main__":
    main()
