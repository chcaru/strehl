#!/usr/bin/env python3
"""Reproduce Strehl's vector master, PNGs and Windows ICO using Python stdlib.

Run with --check to compare every generated byte without modifying assets.
The Rust build consumes checked-in assets and never needs Python.
"""
from pathlib import Path
import argparse
import math
import struct
import sys
import zlib

ROOT = Path(__file__).resolve().parent
SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)
DARK = "#141821"
GOLD = "#e6b450"
# Back to front: three focal planes, with one resolved point on the top plane.
PLANES = (
    (((8, 40), (32, 26), (56, 40), (32, 54)), "#8f7748"),
    (((8, 32), (32, 18), (56, 32), (32, 46)), "#b99a59"),
    (((8, 24), (32, 10), (56, 24), (32, 38)), GOLD),
)
FOCUS = ((25, 24), (32, 20), (39, 24), (32, 28))


def color(hex_value):
    return tuple(bytes.fromhex(hex_value.removeprefix("#"))) + (255,)


class Image:
    def __init__(self, width, height=None, background=(0, 0, 0, 0)):
        self.width = width
        self.height = height or width
        self.pixels = bytearray(bytes(background) * (self.width * self.height))

    def getpixel(self, point):
        x, y = point
        offset = (y * self.width + x) * 4
        return self.pixels[offset:offset + 4]

    def span(self, y, left, right, ink):
        left = max(0, math.ceil(left - 0.5))
        right = min(self.width, math.ceil(right - 0.5))
        if 0 <= y < self.height and left < right:
            offset = (y * self.width + left) * 4
            self.pixels[offset:offset + (right - left) * 4] = bytes(ink) * (right - left)

    def polygon(self, points, ink):
        edges = list(zip(points, points[1:] + points[:1]))
        for y in range(math.floor(min(p[1] for p in points)), math.ceil(max(p[1] for p in points))):
            scan = y + 0.5
            crossings = sorted(x1 + (scan - y1) * (x2 - x1) / (y2 - y1)
                               for (x1, y1), (x2, y2) in edges
                               if min(y1, y2) <= scan < max(y1, y2))
            for left, right in zip(crossings[::2], crossings[1::2]):
                self.span(y, left, right, ink)

    def outline(self, points, ink, width):
        radius = width / 2
        for (x1, y1), (x2, y2) in zip(points, points[1:] + points[:1]):
            length = math.hypot(x2 - x1, y2 - y1)
            dx, dy = -(y2 - y1) * radius / length, (x2 - x1) * radius / length
            self.polygon(((x1 + dx, y1 + dy), (x2 + dx, y2 + dy),
                          (x2 - dx, y2 - dy), (x1 - dx, y1 - dy)), ink)
        for x, y in points:
            for row in range(math.floor(y - radius), math.ceil(y + radius)):
                delta = row + 0.5 - y
                if abs(delta) <= radius:
                    half = math.sqrt(radius * radius - delta * delta)
                    self.span(row, x - half, x + half, ink)

    def paste(self, image, left, top):
        for y in range(image.height):
            for x in range(image.width):
                r, g, b, a = image.getpixel((x, y))
                offset = ((y + top) * self.width + x + left) * 4
                for channel, value in enumerate((r, g, b)):
                    self.pixels[offset + channel] = (value * a + self.pixels[offset + channel] * (255 - a) + 127) // 255
                self.pixels[offset + 3] = 255


def render(size):
    scale = 8
    image = Image(size * scale)
    factor = size * scale / 64
    point = lambda p: tuple(v * factor for v in p)
    # At 16 and 20 px, keep a full physical pixel of edge rather than thinning
    # the mark into an indistinct hairline. The vector master is the large form.
    width = max(size * 3 / 64, 1) * scale
    for vertices, ink in PLANES:
        points = tuple(map(point, vertices))
        image.polygon(points, color(DARK))
        image.outline(points, color(ink), width)
    image.polygon(tuple(map(point, FOCUS)), color(GOLD))
    result = Image(size)
    # Area sampling in premultiplied-alpha space preserves the gold edge on
    # both light and dark desktops without a black fringe or resize ringing.
    for y in range(size):
        for x in range(size):
            red = green = blue = count = 0
            for dy in range(scale):
                offset = (((y * scale + dy) * image.width) + x * scale) * 4
                for dx in range(scale):
                    at = offset + dx * 4
                    if image.pixels[at + 3]:
                        red += image.pixels[at]
                        green += image.pixels[at + 1]
                        blue += image.pixels[at + 2]
                        count += 1
            if count:
                at = (y * size + x) * 4
                result.pixels[at:at + 4] = bytes((round(red / count), round(green / count),
                                                round(blue / count), round(255 * count / scale**2)))
    return result


def png(image):
    def chunk(kind, payload):
        return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload))
    rows = b"".join(b"\0" + image.pixels[y * image.width * 4:(y + 1) * image.width * 4]
                    for y in range(image.height))
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", image.width, image.height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def dib(image):
    """32-bit BGRA + AND mask for native small Windows icon frames."""
    size = image.width
    rows = []
    masks = []
    stride = ((size + 31) // 32) * 4
    for y in reversed(range(size)):
        row = bytearray()
        mask = bytearray(stride)
        for x in range(size):
            r, g, b, a = image.getpixel((x, y))
            row.extend((b, g, r, a))
            if a == 0:
                mask[x // 8] |= 0x80 >> (x % 8)
        rows.append(row)
        masks.append(mask)
    pixels = b"".join(rows)
    header = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, len(pixels), 0, 0, 0, 0)
    return header + pixels + b"".join(masks)


def ico(images):
    frames = [dib(image) if image.width <= 48 else png(image) for image in images]
    offset = 6 + 16 * len(frames)
    entries = []
    for size, payload in zip(SIZES, frames):
        entries.append(struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32, len(payload), offset))
        offset += len(payload)
    return struct.pack("<HHH", 0, 1, len(frames)) + b"".join(entries) + b"".join(frames)


def svg():
    shapes = []
    for vertices, color in PLANES:
        points = " ".join(f"{x},{y}" for x, y in vertices)
        shapes.append(f'  <polygon points="{points}" fill="{DARK}" stroke="{color}" stroke-width="3" stroke-linejoin="round"/>')
    points = " ".join(f"{x},{y}" for x, y in FOCUS)
    shapes.append(f'  <polygon points="{points}" fill="{GOLD}"/>')
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">\n'
            '  <title>Strehl — three focal planes, one resolved point</title>\n'
            + "\n".join(shapes) + "\n</svg>\n").encode()


def preview(images):
    sheet = Image(720, 260, color("#10141c"))
    digits = {
        "0": (7, 5, 5, 5, 7), "1": (2, 6, 2, 2, 7), "2": (7, 1, 7, 4, 7),
        "3": (7, 1, 7, 1, 7), "4": (5, 5, 7, 1, 1), "5": (7, 4, 7, 1, 7),
        "6": (7, 4, 7, 5, 7), "7": (7, 1, 2, 2, 2), "8": (7, 5, 7, 5, 7),
    }
    for row, background in enumerate(("#10141c", "#ededeb")):
        for y in range(row * 130, (row + 1) * 130):
            sheet.span(y, 0, 720, color(background))
        x = 20
        for image in images[:7]:
            sheet.paste(image, x, row * 130 + 28)
            for column, digit in enumerate(str(image.width)):
                for y, bits in enumerate(digits[digit]):
                    for bit in range(3):
                        if bits & (1 << (2 - bit)):
                            at = x + column * 5 + bit
                            sheet.span(row * 130 + 104 + y, at, at + 1, color("#a18a5f"))
            x += image.width + 25
        sheet.paste(images[-2], 580, row * 130 + 1)
    return png(sheet)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    images = [render(size) for size in SIZES]
    files = {"strehl.svg": svg(), "strehl.ico": ico(images), "icon-preview.png": preview(images)}
    files.update({f"strehl-{image.width}.png": png(image) for image in images})
    failed = []
    for name, data in files.items():
        path = ROOT / name
        if options.check:
            if not path.is_file() or path.read_bytes() != data:
                failed.append(name)
        else:
            path.write_bytes(data)
    if failed:
        sys.exit("Icon assets differ: " + ", ".join(failed))
    print(f"{'Verified' if options.check else 'Generated'} {len(files)} icon assets; {len(SIZES)} Windows sizes.")


if __name__ == "__main__":
    main()
